-- Варіант 8. Служба доставки їжі
-- Повний стан бази ПІСЛЯ завершення Практики 4 (див. коментар у
-- v1_result.sql — той самий файл перевикористовується Практикою 5 і
-- далі, до Практики 13). "курʼєри" пишеться через ʼ (модифікатор-літера,
-- не апостроф) — це звичайний символ українського алфавіту, лапки в
-- SQL для нього не потрібні, на відміну від "ім'я" нижче.

PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS замовлення;
DROP TABLE IF EXISTS курʼєри;
DROP TABLE IF EXISTS страви;

CREATE TABLE страви (
    id INTEGER PRIMARY KEY,
    назва TEXT NOT NULL,
    категорія TEXT,
    ціна REAL NOT NULL,
    ресторан TEXT
);

CREATE TABLE курʼєри (
    id INTEGER PRIMARY KEY,
    прізвище TEXT NOT NULL,
    "ім'я" TEXT NOT NULL,
    телефон TEXT,
    транспорт TEXT
);

CREATE TABLE замовлення (
    id INTEGER PRIMARY KEY,
    dish_id INTEGER NOT NULL,
    courier_id INTEGER NOT NULL,
    дата TEXT NOT NULL,
    адреса TEXT NOT NULL,
    статус TEXT NOT NULL DEFAULT 'в дорозі',
    FOREIGN KEY (dish_id) REFERENCES страви (id) ON DELETE RESTRICT,
    FOREIGN KEY (courier_id) REFERENCES курʼєри (id) ON DELETE RESTRICT
);


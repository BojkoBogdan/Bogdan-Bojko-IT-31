-- v1_result.sql — той самий файл перевикористовується Практикою 5 і
-- далі, до Практики 13).

PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS поставки;
DROP TABLE IF EXISTS постачальники;
DROP TABLE IF EXISTS препарати;

CREATE TABLE препарати (
    id INTEGER PRIMARY KEY,
    назва TEXT NOT NULL,
    виробник TEXT,
    форма TEXT,
    ціна REAL NOT NULL,
    кількість_на_складі INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE постачальники (
    id INTEGER PRIMARY KEY,
    назва TEXT NOT NULL,
    контактна_особа TEXT,
    телефон TEXT,
    місто TEXT
);

CREATE TABLE поставки (
    id INTEGER PRIMARY KEY,
    medicine_id INTEGER NOT NULL,
    supplier_id INTEGER NOT NULL,
    дата TEXT NOT NULL,
    кількість INTEGER NOT NULL,
    ціна_закупівлі REAL NOT NULL,
    FOREIGN KEY (medicine_id) REFERENCES препарати (id) ON DELETE RESTRICT,
    FOREIGN KEY (supplier_id) REFERENCES постачальники (id) ON DELETE RESTRICT
);


-- v1_result.sql — той самий файл перевикористовується Практикою 5 і
-- далі, до Практики 13).

PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS продані_абонементи;
DROP TABLE IF EXISTS клієнти;
DROP TABLE IF EXISTS абонементи;

CREATE TABLE абонементи (
    id INTEGER PRIMARY KEY,
    тип TEXT NOT NULL,
    тривалість_днів INTEGER NOT NULL,
    ціна REAL NOT NULL
);

CREATE TABLE клієнти (
    id INTEGER PRIMARY KEY,
    прізвище TEXT NOT NULL,
    "ім'я" TEXT NOT NULL,
    телефон TEXT,
    дата_народження TEXT
);

CREATE TABLE продані_абонементи (
    id INTEGER PRIMARY KEY,
    membership_id INTEGER NOT NULL,
    client_id INTEGER NOT NULL,
    дата_купівлі TEXT NOT NULL,
    дата_закінчення TEXT NOT NULL,
    FOREIGN KEY (membership_id) REFERENCES абонементи (id) ON DELETE RESTRICT,
    FOREIGN KEY (client_id) REFERENCES клієнти (id) ON DELETE RESTRICT
);

